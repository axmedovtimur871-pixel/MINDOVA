  function detect() {
    try {
      const q = new URLSearchParams(location.search).get("lang");
      if (q === "uz" || q === "en") return q;
      const saved = localStorage.getItem(KEY);
      if (saved === "uz" || saved === "en") return saved;
    } catch (e) {}
    const list = (navigator.languages && navigator.languages.length)
      ? navigator.languages
      : [navigator.language || "uz"];
    for (const l of list) {
      if (/^en(-|$)/i.test(l)) return "en";
      if (/^uz(-|$)/i.test(l)) return "uz";
    }
    return "uz";
  }

  let lang = detect();

  function t(key) {
    const v = DICT[lang] && DICT[lang][key];
    if (v != null) return v;
    return (DICT.uz && DICT.uz[key]) || key;
  }

  function apply() {
    document.documentElement.lang = lang;
    const titleKey = document.documentElement.getAttribute("data-i18n-title");
    document.title = t(titleKey || "title");
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-lang]").forEach((btn) => {
      const on = btn.getAttribute("data-lang") === lang;
      btn.classList.toggle("active", on);
      btn.setAttribute("aria-pressed", on ? "true" : "false");
    });
    document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  }

  document.addEventListener("click", (e) => {
    const btn = e.target.closest("[data-lang]");
    if (!btn) return;
    const next = btn.getAttribute("data-lang");
    if ((next !== "uz" && next !== "en") || next === lang) return;
    let saved = true;
    try { localStorage.setItem(KEY, next); } catch (err) { saved = false; }
    try {
      const u = new URL(location.href);
      if (saved) u.searchParams.delete("lang");
      else u.searchParams.set("lang", next);
      location.replace(u.href);
    } catch (err) {
      location.reload();
    }
  });

  window.MI18N = {
    t: t,
    apply: apply,
    detect: detect,
    set: function (l) {
      if (l !== "uz" && l !== "en") return;
      lang = l;
      try { localStorage.setItem(KEY, l); } catch (err) {}
      apply();
    },
    get lang() { return lang; },
    dict: DICT,
  };

  apply();
